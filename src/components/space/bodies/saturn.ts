import { drawEquirect, fillBase, soften, wavyBand } from "../maps";
import type { SpaceBody } from "./common";

/**
 * Сатурн — кольца, тень планеты на них и пара спутников.
 *
 * Кадр на главной странице тоже Сатурн, но собран он иначе: там кольца
 * и планета запечены Canvas2D один раз и не вращаются, а живут только
 * обломки поверх. Здесь всё как у остальных тел сцены — поверхность
 * натянута на шар и уезжает за лимб, кольца считаются в шейдере.
 *
 * Кольца заданы плотностью по радиусу, а не штрихом по контуру: у Сатурна
 * это широкая структура с делением Кассини и щелью Энке, и рисовать её
 * линиями значило бы соврать. Наклон плоскости взят с главной — по нему
 * этот Сатурн и узнаётся.
 */

/** Наклон плоскости колец — тот же, что у кадра на главной */
const TILT = -0.34;

export const saturn: SpaceBody = {
  id: "saturn",
  /** Внешний спутник ходит на 2.9 радиуса планеты — дальше начинается край */
  fit: 1.05,

  buildMap: () =>
    drawEquirect(384, (ctx, box) => {
      fillBase(ctx, box, 0.78);

      // Пояса Сатурна размыты и почти без контраста: в отличие от Юпитера
      // здесь дымка, а не резкие границы. Широты совпадают с границами струй
      // в шейдере, иначе сдвиг рвал бы пояс посередине.
      const bands: readonly [number, number, number][] = [
        [60, 90, 0.6],
        [30, 60, 0.86],
        [18, 30, 0.68],
        [-18, 18, 0.94],
        [-30, -18, 0.7],
        [-60, -30, 0.84],
        [-90, -60, 0.58],
      ];
      bands.forEach(([lat0, lat1, level], i) => {
        wavyBand(ctx, box, {
          lat0,
          lat1,
          level,
          alpha: 0.85,
          waves: 2 + (i % 2),
          amp: 2.5,
          phase: i * 1.7,
        });
      });

      soften(ctx, 5);
    }),

  glsl: /* glsl */ `
const float SATURN_TILT = ${TILT.toFixed(2)};
/** Сжатие эллипса колец: настолько плоскость видна с ребра */
const float SATURN_OPENING = 0.245;
/** Направление на Солнце в плоскости колец — по нему ложится тень */
const vec2 SATURN_SUN = vec2(-0.83, -0.56);
/** Свет уведён вбок сильнее общего: иначе тень на кольцах не видна */
const vec3 SATURN_LIGHT = vec3(-0.62, 0.34, 0.71);

/**
 * Плотность колец на радиусе k, считая в радиусах планеты.
 * Границы настоящие: креповое C, плотное B, деление Кассини, кольцо A
 * со щелью Энке.
 *
 * Ширины подобраны под сетку. На диске в два десятка узлов всё кольцо —
 * это восемь узлов поперёк, и настоящие тысячи колечек в нём просто
 * рассыпались бы в муар: деталь мельче шага сетки сетке не по зубам.
 */
float saturnRings(float k){
  if (k < 1.12 || k > 2.02) return 0.0;

  float v;
  if (k < 1.35)      v = 0.34;  // C — тонкий креп
  else if (k < 1.62) v = 0.95;  // B — самое плотное
  else if (k < 1.74) v = 0.05;  // деление Кассини
  else               v = 0.64;  // A

  // Внешний край A растворяется, а не обрывается
  v *= 1.0 - 0.3 * smoothstep(1.9, 2.02, k);
  // Крупная волна плотности: тысячи настоящих колечек сетке не по зубам
  v *= 0.92 + 0.08 * sin(k * 14.0);
  return v;
}

/** Экваториальная струя Сатурна вторая по скорости в системе */
float saturnJet(float latDeg){
  float a = abs(latDeg);
  if (a > 60.0) return 1.0;
  if (a > 30.0) return 1.6;
  if (a > 18.0) return 2.2;
  return 3.4;
}

float field(vec2 p){
  vec2 q = p - uCenter;
  float R = uScale * 0.32;

  // Точка экрана однозначно ложится в плоскость колец: плоскость проецируется
  // на экран один в один, а знак rq.y говорит, ближняя это половина или дальняя
  vec2 rq = rot(q, -SATURN_TILT);
  vec2 ring = vec2(rq.x, rq.y / SATURN_OPENING);
  float rings = saturnRings(length(ring) / R);

  // Тень планеты падает на кольца с противосолнечной стороны
  float along = dot(ring, SATURN_SUN);
  if (along < 0.0 && length(ring - SATURN_SUN * along) < R) rings *= 0.12;

  float v;
  float lon, lat;
  vec3 n;

  // Диск заметно сплюснут: Сатурн самая приплюснутая планета системы
  if (sphereAt(vec2(q.x, q.y / 0.9), R, lon, lat, n)){
    float latDeg = lat * 180.0 / PI;
    float albedo = contrast(mapAt(lon + uTime * 0.08 * saturnJet(latDeg), lat), 1.25, 0.72);
    v = clamp(albedo * lit(n, 0.16, SATURN_LIGHT), 0.0, 1.0);
    // Ближняя половина колец ложится поверх диска, дальняя уходит за него
    if (rq.y < 0.0) v = max(v, rings);
  } else {
    v = rings;
  }

  // Спутники в плоскости колец: Титан и соседи
  for (int i = 0; i < 3; i++){
    float fi = float(i);
    float orbit = R * (2.3 + fi * 0.3);
    float a = 1.1 + fi * 2.3 + uTime * 0.26 / pow(1.0 + fi, 1.5);
    vec2 moon = vec2(cos(a) * orbit, sin(a) * orbit * SATURN_OPENING);
    if (sin(a) > 0.0 && length(moon) < R) continue;
    v = max(v, dot2(rq, moon, 1.15 - fi * 0.15) * 0.9);
  }

  return v;
}
`,
};
