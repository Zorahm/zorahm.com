import type { BodyId } from "@/content";

/**
 * Тело сцены /space глазами рендера.
 *
 * Устроено так же, как фигуры главной страницы: статика рисуется один раз
 * на Canvas2D, живое считает шейдер. Разница в том, что статика тела — это
 * карта поверхности в координатах «долгота × широта», и шейдер натягивает
 * её на шар, а не показывает как есть. Всё, что не поверхность — кольца,
 * спутники, корона, — живёт прямо в шейдере и потому масштабируется вместе
 * с телом, пока камера к нему летит.
 */
export type SpaceBody = {
  id: BodyId;
  /**
   * Опорный масштаб тела в долях масштаба сетки. Композиции разного размаха
   * (голый диск Меркурия и система Сатурна с кольцами и спутниками) этим
   * множителем приводятся к одному росту в кадре.
   */
  fit: number;
  /** Карта поверхности: канал R — основной слой, G — второй, если он нужен */
  buildMap?: () => HTMLCanvasElement;
  /** Тело шейдера: обязано определить float field(vec2 node) */
  glsl: string;
};
