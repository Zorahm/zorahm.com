/**
 * Пояс мелких тел. Границы заданы в тех же астрономических единицах, что и
 * орбиты планет, и проходят через то же сжатие: астероидный оказывается
 * между Марсом и Юпитером не потому, что его туда поставили, а потому что
 * он там и лежит.
 */
/**
 * Особенность в радиальном распределении вещества: щель или, наоборот, навал.
 *
 * И то и другое делает одна и та же причина — резонанс с большой планетой,
 * поэтому и описываются они одним типом, отличаясь только знаком. Там, где
 * резонанс раскачивает орбиту, вещество выметено (щели Кирквуда в поясе
 * астероидов); там, где он её удерживает, вещество накапливается (плутино
 * на 2:3 с Нептуном). Пояс без этого рисунка — просто баранка.
 */
export type BeltFeature = {
  /** Радиус в астрономических единицах */
  au: number;
  /** Полуширина в астрономических единицах */
  width: number;
  /** Минус — щель, плюс — навал; единица примерно равна полному выметанию */
  amount: number;
  /** Чем вызвана: резонанс и с кем */
  why: string;
};

export type Belt = {
  id: "asteroid" | "kuiper";
  /** Внутренняя и внешняя граница в астрономических единицах */
  span: [number, number];
  /** Те же границы в единицах сцены */
  inner: number;
  outer: number;
  /** Полутолщина слоя: пояса плоские, но не бесконечно */
  height: number;
  /** Доля занятых ячеек решётки: чем больше, тем гуще россыпь */
  density: number;
  /** Размер ячейки в единицах сцены — по камню на ячейку */
  cell: number;
  /** Щели и навалы по радиусу. Шейдер разбирает первые BELT_FEATURE_SLOTS */
  features: BeltFeature[];
  color: Vec3;
};

