/** Сколько щелей разбирает шейдер: столько же чисел приходит юниформой */
export const BELT_GAP_SLOTS = 3;

/**
 * Место щелей внутри пояса в долях его ширины — в этом виде их и ждёт
 * шейдер. Пустые места заполнены единицей с запасом: там колокол щели
 * уже неотличим от нуля, и лишняя ветка в цикле не нужна.
 */
export const beltGapSlots = (belt: Belt): number[] =>
  Array.from({ length: BELT_GAP_SLOTS }, (_, i) => {
    const au = belt.gaps[i];
    if (au === undefined) return -1;
    return (sceneOrbit(au) - belt.inner) / (belt.outer - belt.inner);
  });

/** Место тела в композиции по идентификатору */
export const bodyIndex = (id: BodyId) =>
  SYSTEM_3D.findIndex((body) => body.id === id);
