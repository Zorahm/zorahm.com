import type { BodyId } from "@/content";

/**
 * Композиция трассированной сцены: где тело летает, какого оно размера
 * и из чего сделана его поверхность.
 *
 * Это второй набор чисел про те же девять тел, и так и задумано. Точечная
 * сцена /space живёт в узлах сетки и рисует диски; здесь у тел есть радиус
 * в единицах сцены, ось вращения и цвет — величины, которых точкам не нужно.
 * Общее у двух сцен ровно одно: идентификатор тела, по нему подтягиваются
 * тексты. Порядок тоже общий и проверяется тестом.
 *
 * Пропорции художественные, как и на точечной сцене: в настоящем масштабе
 * Солнце было бы в сто девять раз больше Земли, Нептун — в трёх тысячах
 * солнечных радиусов от него, и на экране остался бы один пиксель посреди
 * пустоты. Сохранены порядок тел, разрыв на месте пояса астероидов и третий
 * закон Кеплера: чем дальше орбита, тем медленнее обращение.
 *
 * Оси координат: XZ — плоскость эклиптики, Y — на север.
 */

/**
 * Как шейдер рисует поверхность. Число уходит в юниформу и разбирается
 * там ветвлением, поэтому значения обязаны совпадать с константами
 * в glsl/surfaces.ts — это проверяется тестом.
 */
export const Surface = {
  /** Солнце: гранулы, потемнение к лимбу, корона */
  Sun: 0,
  /** Каменное тело: кратеры и реголит */
  Rock: 1,
  /** Газовый гигант: струйные пояса и вихри */
  Gas: 2,
  /** Земля: материки, океан с бликом, облака и огни ночной стороны */
  Earth: 3,
  /** Ледяной гигант: ровная дымка с редкими штормами */
  Ice: 4,
  /** Венера: сплошная облачная пелена */
  Cloud: 5,
} as const;

export type Surface = (typeof Surface)[keyof typeof Surface];

/**
 * Как устроены кольца. Профилей два, и они не взаимозаменяемы: широкая
 * структура с делениями — это Сатурн, десяток тёмных нитей — Уран.
 */
export const RingStyle = {
  /** Сплошной диск с делением Кассини и щелью Энке */
  Broad: 0,
  /** Узкие нити тёмного вещества, из которых различимо только эпсилон */
  Narrow: 1,
} as const;

export type RingStyle = (typeof RingStyle)[keyof typeof RingStyle];

export type Rings = {
  /** Внутренний и внешний радиус в радиусах тела */
  span: [number, number];
  style: RingStyle;
};

export type Vec3 = [number, number, number];

export type Body3D = {
  id: BodyId;
  /** Радиус тела в единицах сцены */
  radius: number;
  /** Радиус орбиты; у Солнца 0 */
  orbit: number;
  /** Фаза на орбите при нулевом времени, радианы */
  phase: number;
  /** Наклон оси вращения к нормали эклиптики, радианы */
  tilt: number;
  /** Оборотов вокруг оси в секунду сцены; отрицательное — обратное вращение */
  spin: number;
  /** Основной цвет поверхности */
  colorA: Vec3;
  /** Второй цвет: пояса, материки, тени в рисунке */
  colorB: Vec3;
  style: Surface;
  /** Частота рисунка поверхности: число поясов, размер кратеров */
  detail: number;
  /** Контраст рисунка: у Юпитера резкие границы, у Сатурна дымка */
  contrast: number;
  /**
   * Добавка стиля. Значение зависит от поверхности: доля облаков у Земли,
   * полярные шапки у Марса, Красное пятно у Юпитера, шторм у Нептуна.
   */
  extra: number;
  /** Кольца, если они есть */
  rings?: Rings;
  /** С какого расстояния камера смотрит на тело, в его радиусах */
  framing: number;
  /**
   * Подъём камеры при залёте, радианы. Задаётся там, где угол зрения решает
   * дело: кольца Сатурна с ребра — это линия, и подходить к нему надо сверху.
   */
  viewPhi?: number;
};

/**
 * Спутник. Радиус и орбита заданы в радиусах родителя, поэтому композиция
 * не разъезжается, если планету придётся укрупнить.
 */
export type Moon = {
  parent: BodyId;
  /** Радиус в радиусах родителя */
  radius: number;
  /** Радиус орбиты в радиусах родителя */
  orbit: number;
  phase: number;
  /** Оборотов в секунду сцены; отрицательное — обратное движение */
  rate: number;
  color: Vec3;
  /** Частота рисунка поверхности */
  detail: number;
};

