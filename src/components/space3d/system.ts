/** Сколько особенностей разбирает шейдер: столько же чисел приходит юниформой */
export const BELT_FEATURE_SLOTS = 4;

/**
 * Щели и навалы в том виде, в каком их ждёт шейдер: три четвёрки чисел —
 * места, полуширины и величины. Место и ширина считаются в долях ширины
 * пояса, потому что в шейдере радиус уже нормирован.
 *
 * Полуширина переносится через то же сжатие, что и радиус, а не делится
 * на него: у внешнего края корень идёт положе, и одна и та же щель в
 * астрономических единицах занимает там меньше кадра.
 *
 * Пустые места получают нулевую величину: колокол в них считается, но
 * ни на что не влияет, и ветки в цикле не нужно.
 */
export const beltFeatureSlots = (belt: Belt) => {
  const span = belt.outer - belt.inner;
  const slots = Array.from(
    { length: BELT_FEATURE_SLOTS },
    (_, i) => belt.features[i],
  );

  return {
    at: slots.map((f) => (f ? (sceneOrbit(f.au) - belt.inner) / span : 0)),
    width: slots.map((f) =>
      f
        ? Math.max(
            1e-4,
            (sceneOrbit(f.au + f.width) - sceneOrbit(f.au - f.width)) /
              (2 * span),
          )
        : 1,
    ),
    amount: slots.map((f) => (f ? f.amount : 0)),
  };
};

