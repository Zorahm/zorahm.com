/**
 * Звёздное небо.
 *
 * Главное здесь — размер звезды задан в пикселях, а не в мире. Ядро держится
 * чуть шире пикселя при любом разрешении сцены, поэтому звёзды остаются
 * точками и не расплываются, когда подстройка роняет масштаб рендера.
 * Ореол оставлен только ярким: именно он отличает звезду от точки, но если
 * раздать его всем, небо превращается в молоко.
 *
 * Звёзд примерно шесть тысяч на всю сферу — столько же различает глаз в
 * идеальную ночь. Больше не нужно: лишние сливаются в фон и съедают контраст,
 * ради которого всё и затевалось.
 *
 * Мерцания нет. Оно берётся от атмосферы, а камера находится в вакууме —
 * здесь звёзды стоят намертво.
 */
export const STARS = /* glsl */ `
uniform float uStars;

/** Угловой размер пикселя сцены */
float pixelAngle(){
  return uTanFov * 2.0 / uRes.y;
}

/** Цвет по температуре: от красного карлика до голубого гиганта */
vec3 starTint(float t){
  vec3 red   = vec3(1.00, 0.54, 0.34);
  vec3 amber = vec3(1.00, 0.82, 0.62);
  vec3 white = vec3(1.00, 0.97, 0.94);
  vec3 blue  = vec3(0.70, 0.81, 1.00);
  vec3 c = mix(red, amber, smoothstep(0.00, 0.28, t));
  c = mix(c, white, smoothstep(0.24, 0.62, t));
  c = mix(c, blue,  smoothstep(0.62, 1.00, t));
  return c;
}

/**
 * Слой звёзд: решётка ячеек, в занятых лежит по звезде со случайным
 * смещением внутри ячейки — регулярность сетки от этого не читается.
 *
 * spikes включает лучи у самых ярких. Они появляются от диафрагмы объектива,
 * поэтому идут по экрану, а не по миру, и смещение до звезды раскладывается
 * по осям камеры.
 */
vec3 starLayer(vec3 rd, vec3 right, vec3 up, float scale, float thresh,
               float gain, float spikes){
  vec3 p  = rd * scale;
  vec3 id = floor(p);
  vec3 h  = hash33(id);
  if (h.x > thresh) return vec3(0.0);

  vec3 off   = (hash33(id + 11.7) - 0.5) * 0.8;
  vec3 delta = (fract(p) - 0.5 - off) / scale;

  // Смещение в пикселях экрана — только по нему и считается пятно
  vec2  sp = vec2(dot(delta, right), dot(delta, up)) / pixelAngle();
  float r2 = dot(sp, sp);
  if (r2 > 400.0) return vec3(0.0);

  // Ярких мало, тусклых много
  float mag  = pow(h.y, 7.0);
  // Ядро чуть шире пикселя: уже — и звёзды замигают при повороте камеры
  float core = 1.05 + 0.8 * mag;

  float light = exp(-r2 / (2.0 * core * core));
  // Ореол у ярких, и только у них
  light += mag * 0.12 * exp(-r2 / (18.0 * core * core));

  if (spikes > 0.0 && mag > 0.5){
    float spread = 1.5 + 6.0 * mag;
    float cross  = exp(-sp.y * sp.y / (0.4 * core))
                 + exp(-sp.x * sp.x / (0.4 * core));
    light += cross * exp(-r2 / (2.0 * spread * spread)) * mag * spikes * 0.3;
  }

  // Порог отбора яркого проходят единицы: если свечение достаётся всем,
  // небо снова превращается в туман, только уже из ореолов
  return starTint(pow(h.z, 0.7)) * light * (0.05 + 0.95 * mag) * gain;
}

/**
 * Млечный Путь: полоса неразрешённых звёзд с тёмными пылевыми прожилками.
 *
 * Полоса нарочно узкая и слабая. Широкая дымка поперёк неба — ровно то, из-за
 * чего фон переставал быть фоном и лез вперёд планет.
 */
vec3 galaxy(vec3 rd){
  vec3  pole = normalize(vec3(0.34, 0.86, -0.38));
  float lat  = dot(rd, pole);
  float band = exp(-lat * lat * 32.0);
  if (band < 0.002) return vec3(0.0);

  // Крупная пятнистость и мелкое зерно: неразрешённые звёзды сбиваются
  // в облака, и у облаков есть своя структура
  float mottle = fbm4(rd * 9.0 + 4.0);
  float grain  = fbm4(rd * 27.0 - 2.0);
  // Пыль режет полосу вдоль и темнее её самой
  float dust   = smoothstep(0.44, 0.63, fbm4(rd * 6.0 + vec3(0.0, 3.0, 0.0)));

  float level = band * (0.30 + 0.95 * mottle * mottle) * (0.55 + 0.7 * grain);
  level *= 1.0 - 0.75 * dust * band;

  vec3 warm = vec3(0.88, 0.82, 0.72);
  vec3 cool = vec3(0.54, 0.63, 0.86);
  return mix(cool, warm, mottle) * level * 0.05;
}

vec3 background(vec3 rd){
  vec3 right = uCamMat[0];
  vec3 up    = uCamMat[1];

  // Три слоя: редкие яркие, обычные и мелочь у порога различимости
  vec3 col = starLayer(rd, right, up,  26.0, 0.035, 1.6, 1.0)
           + starLayer(rd, right, up,  60.0, 0.030, 0.7, 0.0)
           + starLayer(rd, right, up, 130.0, 0.020, 0.45, 0.0);

  col = (col + galaxy(rd)) * uStars;

  // Межзвёздная среда: небо нигде не бывает абсолютно чёрным
  return col + vec3(0.0025, 0.0035, 0.007);
}
`;
